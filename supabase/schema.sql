-- Migration policy: players imported from the existing club roster are permanent.
-- Do not delete their existing registration/history. Import the existing users first,
-- then use the admin migration statement below to approve them as permanent.
-- This intentionally does not auto-promote newly registered users.


create table if not exists public.legacy_player_roster (
  id bigint generated by default as identity primary key,
  full_name text not null unique,
  player_type text not null default 'permanent' check (player_type='permanent'),
  migration_status text not null default 'pending_link' check (migration_status in ('pending_link','linked')),
  linked_user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.legacy_player_roster enable row level security;
create policy "legacy roster admin only" on public.legacy_player_roster for all using (public.is_admin()) with check (public.is_admin());
