-- Player-submitted absence reports; email is fixed to the verified club Admin.
create table public.absence_reports (
 id bigint generated by default as identity primary key,
 reporter_id uuid not null references public.profiles(id) on delete cascade,
 player_name text not null check(length(btrim(player_name)) between 1 and 120),
 location text not null check(length(btrim(location)) between 1 and 180),
 court text not null check(length(btrim(court)) between 1 and 80),
 session_date date not null,
 session_label text not null check(length(btrim(session_label)) between 1 and 120),
 notes text check(length(notes)<=1500),
 created_at timestamptz not null default now()
);
create unique index absence_report_duplicate on public.absence_reports
 (reporter_id,session_date,lower(btrim(player_name)),lower(btrim(location)),lower(btrim(court)),lower(btrim(session_label)));
alter table public.absence_reports enable row level security;
revoke all on public.absence_reports from anon,authenticated;
grant select,insert on public.absence_reports to authenticated;
grant usage on sequence public.absence_reports_id_seq to authenticated;
create policy absence_report_read on public.absence_reports for select to authenticated
 using(reporter_id=(select auth.uid()) or public.is_admin());
create policy absence_report_insert on public.absence_reports for insert to authenticated
 with check(reporter_id=(select auth.uid()) and exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.player_type_status<>'rejected'));

create schema if not exists kestrel_reports;
revoke all on schema kestrel_reports from public,anon,authenticated;
-- Only this trigger may write to the private outbound email queue.
create function kestrel_reports.queue_absence_email() returns trigger
 language plpgsql security definer set search_path='' as $$
declare recipient uuid; reporter_name text; reporter_email text;
begin
 if auth.uid() is null or auth.uid()<>new.reporter_id then raise exception 'Sign in to submit your own report'; end if;
 select p.id into recipient from public.profiles p where p.is_admin and lower(p.email)='academynewstar@gmail.com' limit 1;
 if recipient is null then raise exception 'Admin email is not configured. Please contact Admin through Messages.'; end if;
 select p.full_name,p.email into reporter_name,reporter_email from public.profiles p where p.id=new.reporter_id;
 insert into public.email_notifications(user_id,notification_type,recipient_email,subject,body)
 values(recipient,'absence_report','academynewstar@gmail.com',
 'Absence report - '||new.session_date::text||' - Kestrel Sports',
 'A player has reported an absence for Admin review.'||chr(10)||chr(10)||
 'Absent player: '||btrim(new.player_name)||chr(10)||
 'Location / school: '||btrim(new.location)||chr(10)||
 'Court / team: '||btrim(new.court)||chr(10)||
 'Session date: '||new.session_date::text||' (Toronto)'||chr(10)||
 'Session / time: '||btrim(new.session_label)||chr(10)||
 'Reported issue: Player is not attending and has not marked Not Going.'||chr(10)||
 'Additional details: '||coalesce(nullif(btrim(new.notes),''),'None')||chr(10)||chr(10)||
 'Reported by: '||coalesce(reporter_name,'Player')||chr(10)||
 'Reporter email: '||coalesce(reporter_email,'Not available')||chr(10)||
 'Report ID: '||new.id::text||chr(10)||
 'Submitted: '||to_char(now() at time zone 'America/Toronto','YYYY-MM-DD HH24:MI')||' Toronto time'||chr(10)||chr(10)||
 'Please verify the report before changing attendance or account status.');
 return new;
end $$;
revoke all on function kestrel_reports.queue_absence_email() from public,anon,authenticated;
create trigger queue_absence_email after insert on public.absence_reports
 for each row execute function kestrel_reports.queue_absence_email();
